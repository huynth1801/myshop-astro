package com.shop.sepay;

import com.shop.order.Order;
import com.shop.order.OrderRepository;
import com.shop.order.OrderService;
import com.shop.order.OrderStatus;
import com.shop.order.PaymentMethod;
import java.util.Locale;
import java.util.Optional;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

/**
 * Automated VietQR reconciliation (PLAN.md §12, ADR 0008): match an incoming
 * bank transfer to its order and confirm it without admin intervention.
 *
 * Matching rules:
 * - the transfer description must contain the order code (MS-YYMMDD-XXXXXX,
 *   generated by VietQrService as "THANH TOAN &lt;code&gt;");
 * - the transferred amount must equal the order total exactly (whole VND);
 * - only PENDING VIETQR orders auto-confirm; everything else is reported for
 *   manual handling instead of being silently swallowed.
 *
 * Idempotency: once an order leaves PENDING the webhook is a no-op, so SePay
 * retries and duplicate deliveries can never double-process an order.
 */
@Service
public class SepayPaymentService {

    private static final Logger log = LoggerFactory.getLogger(SepayPaymentService.class);

    // Lenient on purpose: customers type the code into their banking app, so
    // match case-insensitively and allow 1–8 suffix chars, then normalize —
    // the lookup itself stays exact.
    private static final Pattern ORDER_CODE = Pattern.compile("(?i)\\bMS-\\d{6}-[A-Z0-9]{1,8}\\b");

    private final OrderRepository orderRepository;
    private final OrderService orderService;

    public SepayPaymentService(OrderRepository orderRepository, OrderService orderService) {
        this.orderRepository = orderRepository;
        this.orderService = orderService;
    }

    public SepayMatchResult reconcile(SepayWebhookRequest event) {
        if (event.transferType() != null && !"in".equalsIgnoreCase(event.transferType())) {
            return SepayMatchResult.ignored("Không phải chuyển khoản đến (transferType=" + event.transferType() + ")");
        }
        Matcher matcher = ORDER_CODE.matcher(event.content());
        if (!matcher.find()) {
            return SepayMatchResult.ignored("Nội dung chuyển khoản không chứa mã đơn hàng");
        }
        String orderCode = matcher.group().toUpperCase(Locale.ROOT);

        Optional<Order> found = orderRepository.findByOrderCode(orderCode);
        if (found.isEmpty()) {
            log.warn("[SePay] Transfer of {} VND references unknown order code {}", event.transferAmount(), orderCode);
            return SepayMatchResult.notFound(orderCode);
        }

        Order order = found.get();
        return switch (order.getStatus()) {
            case PENDING -> settlePending(order, event);
            case CONFIRMED, PAID, SHIPPING, FULFILLED -> SepayMatchResult.alreadyProcessed(orderCode);
            case CANCELLED, REFUNDED -> {
                log.error("[SePay] Received {} VND for {} order {} — manual handling required",
                        event.transferAmount(), order.getStatus(), orderCode);
                yield SepayMatchResult.manualReview(orderCode,
                        "Đơn đã " + order.getStatus() + " — cần đối chiếu và hoàn tiền thủ công");
            }
        };
    }

    private SepayMatchResult settlePending(Order order, SepayWebhookRequest event) {
        String orderCode = order.getOrderCode();
        long expectedVnd = order.getTotalCents() / 100;
        if (event.transferAmount() != expectedVnd) {
            log.error("[SePay] Amount mismatch for {}: received {} VND, expected {} VND",
                    orderCode, event.transferAmount(), expectedVnd);
            return SepayMatchResult.amountMismatch(orderCode,
                    "Sai số tiền: nhận " + event.transferAmount() + " VND, đơn cần " + expectedVnd + " VND");
        }
        if (order.getPaymentMethod() != PaymentMethod.VIETQR) {
            log.error("[SePay] Bank transfer received for {} order {} — manual handling required",
                    order.getPaymentMethod(), orderCode);
            return SepayMatchResult.manualReview(orderCode,
                    "Đơn thanh toán bằng " + order.getPaymentMethod() + " — cần xử lý thủ công");
        }
        orderService.updateOrderStatus(order.getId(), OrderStatus.CONFIRMED);
        log.info("[SePay] Order {} auto-confirmed — {} VND received", orderCode, event.transferAmount());
        return SepayMatchResult.confirmed(orderCode);
    }
}
